"""Front panel board: 3 buttons and 3 LEDs, cabled to the backplane J24 with a 12-wire IDC ribbon.

Writes PanelRevA/ (schematic + PCB). Run with KiCad's python. The resistors stay on the backplane.
J1 sits on the back side, at the top, so the two M3 holes are at the same distance from the
outer buttons. Seen from the front its pin order is mirrored: pair 1/2 is on the right. A standard
IDC ribbon connects pin N to pin N. Button tracks are on F.Cu, LED tracks on B.Cu; the LED order
(USER, DISK, POWER from the left) and the LEDs turned with the cathode on the right keep the six
B.Cu tracks free of crossings.
"""
import math
import os
import shutil
import sys
import uuid

import pcbnew

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import design as D  # noqa: E402
import build_sch as S  # noqa: E402
from build_pcb import V, MM, Router, add_rect, add_text, pad_xy, zone  # noqa: E402

PROJECT = "MisterFlat_Panel_RevA"
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "PanelRevA")
ROOT = str(uuid.uuid5(S.NS, "panel-root-sheet"))

W, H = 48.0, 32.0            # board size
OX, OY = 100.0, 100.0        # board origin on the KiCad page
COLS = (12.0, 24.0, 36.0)    # button / LED column centres
BTN_SIG_Y, BTN_GND_Y = 13.75, 18.25
LED_Y = 25.5
PITCH = 2.54
HDR_ODD_Y, HDR_EVEN_Y = 7.0, 7.0 - PITCH
HDR_PAIR1_X = W / 2 + 2.5 * PITCH       # pins 1/2; pins 11/12 are 5 pitches to the left
HOLES = {"H1": (3.5, H / 2), "H2": (W - 3.5, H / 2)}


def P(x, y):
    return (OX + x, OY + y)


# Column k holds button BUTTONS[k] above LED LEDS[k].
BUTTONS = ["RESET", "OSD", "USER"]
LEDS = ["LED USER", "LED DISK", "LED POWER"]


def net_names():
    """J1 pin -> net, same pin use as J24 on the backplane."""
    nets = {}
    for i, (name, _pin, kind) in enumerate(D.PANEL):
        q = 5 - i
        tag = name.replace(" ", "_")
        if kind == "btn":
            nets[str(2 * q + 1)], nets[str(2 * q + 2)] = f"BTN_{tag}", "GND"
        else:
            nets[str(2 * q + 1)], nets[str(2 * q + 2)] = f"{tag}_K", f"{tag}_A"
    return nets


J1_NETS = net_names()


def parts():
    p = {"J1": ("IDC 2x6 to backplane J24", "Connector_Generic:Conn_02x06_Odd_Even",
                "Connector_IDC:IDC-Header_2x06_P2.54mm_Vertical", dict(J1_NETS), {})}
    for k, name in enumerate(BUTTONS):
        p[f"SW{k + 1}"] = (name, "Switch:SW_Push", "Button_Switch_THT:SW_PUSH_6mm_H13mm",
                           {"1": f"BTN_{name}", "2": "GND"}, {"MPN": "6x6 mm tactile switch, 13 mm high"})
    for k, name in enumerate(LEDS):
        tag = name.replace(" ", "_")
        p[f"D{k + 1}"] = (name, "Device:LED", "LED_THT:LED_D3.0mm",
                          {"1": f"{tag}_K", "2": f"{tag}_A"}, {"MPN": "3 mm LED, 2 mA is enough (1k on the backplane)"})
    for ref in HOLES:
        p[ref] = ("M3", "Mechanical:MountingHole", "MountingHole:MountingHole_3.2mm_M3", {}, {})
    return p


PARTS = parts()


def build_sch():
    sh = S.Sheet(project=PROJECT, root=ROOT)
    g = 2.54
    v, sym, fp, nets, f = PARTS["J1"]
    sh.symbol("J1", sym, 30 * g, 30 * g, v, fp, nets, f)
    for k in range(3):
        for ref, y in ((f"SW{k + 1}", 20 * g), (f"D{k + 1}", 40 * g)):
            v, sym, fp, nets, f = PARTS[ref]
            sh.symbol(ref, sym, (60 + 16 * k) * g, y, v, fp, nets, f)
    for i, ref in enumerate(HOLES):
        v, sym, fp, nets, f = PARTS[ref]
        sh.symbol(ref, sym, (60 + 8 * i) * g, 55 * g, v, fp, nets, f, in_bom=False)
    sh.pwr_flag("GND", 30 * g, 50 * g, 1)
    sh.text("Front panel board. J1 gets a 12-wire IDC ribbon from J24 on the backplane (pin N to pin N).\n"
            "Buttons pull the FPGA pin to GND (10k pull-ups on the backplane). LEDs: anode from 3V3 through 1k\n"
            "on the backplane, cathode to the FPGA pin.", 10 * g, 8 * g, 1.5)
    title = ('(title_block (title "MisterFlat front panel board") (date "2026-10-20") (rev "A") '
             '(company "PROTOTYPE") (comment 1 "Generated by tools/build_panel.py"))')
    sh.write(os.path.join(OUT, f"{PROJECT}.kicad_sch"), paper="A4", title=title)
    print("schematic ok", len(sh.items), "items")
    return {ref: S.uid("sym", ref) for ref in PARTS}


def place(board, nets, ref, sym_uuid):
    value, _sym, fpid, pinnets, fields = PARTS[ref]
    lib, name = fpid.split(":")
    fp = pcbnew.FootprintLoad(os.path.join(D.KICAD_FP, lib + ".pretty"), name)
    assert fp, fpid
    fp.SetFPID(pcbnew.LIB_ID(lib, name))
    fp.SetReference(ref)
    fp.SetValue(value)
    fp.SetPath(pcbnew.KIID_PATH(f"/{sym_uuid}"))
    fp.SetSheetname("/")
    fp.SetSheetfile(f"{PROJECT}.kicad_sch")
    board.Add(fp)
    fp.SetField("Datasheet", "~")
    for k, v in fields.items():
        fp.SetField(k, v)
        fp.GetField(k).SetVisible(False)
    for pad in fp.Pads():
        if pad.GetNumber() in pinnets:
            pad.SetNet(nets[pinnets[pad.GetNumber()]])
    fp.Value().SetVisible(False)
    return fp


def put(fp, pin, at, want, flip=False):
    """Rotate (and flip) so pad `pin` is at `at` and each pad in `want` is at its offset from it."""
    if flip:
        fp.Flip(fp.GetPosition(), pcbnew.FLIP_DIRECTION_LEFT_RIGHT)
    base = fp.GetOrientationDegrees()
    for rot in (0, 90, 180, 270):
        fp.SetOrientationDegrees(base + rot)
        fp.SetPosition(V(0, 0))
        p0 = pad_xy(fp, pin)
        fp.SetPosition(V(at[0] - p0[0], at[1] - p0[1]))
        if all(any(abs(pp.GetPosition().x - MM(at[0] + dx)) < 10 and abs(pp.GetPosition().y - MM(at[1] + dy)) < 10
                   for pp in fp.Pads() if pp.GetNumber() == n) for n, (dx, dy) in want.items()):
            return
    raise SystemExit(f"{fp.GetReference()}: no orientation")


def hdr(pin):
    """Position of J1 pin `pin`: odd pins on the lower row, pair 1/2 on the right."""
    q = (pin - 1) // 2
    return P(HDR_PAIR1_X - PITCH * q, HDR_ODD_Y if pin % 2 else HDR_EVEN_Y)


def build_pcb(uuids):
    board = pcbnew.BOARD()
    board.SetCopperLayerCount(2)
    tb = board.GetTitleBlock()
    tb.SetTitle("MisterFlat front panel board")
    tb.SetRevision("A")
    tb.SetDate("2026-10-20")
    tb.SetCompany("PROTOTYPE")
    names = sorted({n for p in PARTS.values() for n in p[3].values()})
    nets = {}
    for n in names:
        ni = pcbnew.NETINFO_ITEM(board, n)
        board.Add(ni)
        nets[n] = ni
    fps = {ref: place(board, nets, ref, uuids[ref]) for ref in PARTS}

    put(fps["J1"], "1", hdr(1), {"2": (0, -PITCH), "3": (-PITCH, 0)}, flip=True)
    for k, c in enumerate(COLS):
        # signal pads on the upper row, towards the header
        put(fps[f"SW{k + 1}"], "1", P(c - 3.25, BTN_SIG_Y), {"2": (0, BTN_GND_Y - BTN_SIG_Y)})
        put(fps[f"D{k + 1}"], "1", P(c + 1.27, LED_Y), {"2": (-2.54, 0)})
    for ref, (x, y) in HOLES.items():
        fps[ref].SetPosition(V(*P(x, y)))
        fps[ref].Reference().SetVisible(False)

    for a, b in (((0, 0), (W, 0)), ((W, 0), (W, H)), ((W, H), (0, H)), ((0, H), (0, 0))):
        s = pcbnew.PCB_SHAPE(board)
        s.SetShape(pcbnew.SHAPE_T_SEGMENT)
        s.SetStart(V(*P(*a)))
        s.SetEnd(V(*P(*b)))
        s.SetLayer(pcbnew.Edge_Cuts)
        s.SetWidth(MM(0.1))
        board.Add(s)

    r = Router(board, nets)
    F, B = pcbnew.F_Cu, pcbnew.B_Cu
    w = 0.25
    pin = {n: hdr(int(p)) for p, n in J1_NETS.items()}
    # Buttons on F.Cu: link both signal pads, then up to the lower header row.
    for k, name in enumerate(BUTTONS):
        c = OX + COLS[k]
        r.track([(c - 3.25, OY + BTN_SIG_Y), (c + 3.25, OY + BTN_SIG_Y)], w, F, f"BTN_{name}")
    t = pin["BTN_RESET"]
    x0 = OX + COLS[0] + 3.25
    r.track([(x0, OY + BTN_SIG_Y), (x0, t[1] + (t[0] - x0)), t], w, F, "BTN_RESET")
    t = pin["BTN_OSD"]
    x0 = OX + COLS[1] - 3.25
    r.track([(x0, OY + BTN_SIG_Y), (x0, t[1] + 1.0), t], w, F, "BTN_OSD")
    t = pin["BTN_USER"]
    x0 = OX + COLS[2] - 3.25
    r.track([(x0, OY + BTN_SIG_Y), (x0, OY + 10.0), (t[0] + 1.0, OY + 10.0), (t[0], OY + 9.0), t],
            w, F, "BTN_USER")
    # LEDs on B.Cu: six tracks in planar order. Each one rises from its pad to a lane under the
    # buttons, runs to a channel under the OSD button body, goes up, turns right at its own height
    # (the right-most turns lowest) and reaches its pin. Anodes pass between the lower-row pads.
    order = []
    for k, name in enumerate(LEDS):
        tag = name.replace(" ", "_")
        c = OX + COLS[k]
        order += [(f"{tag}_A", c - 1.27), (f"{tag}_K", c + 1.27)]
    chan0, chan_p = OX + 22.6, 0.55
    lanes = {0: 20.2, 1: 20.9, 2: 21.6, 3: 21.6, 4: 20.9, 5: 20.2}
    for i, (net, sx) in enumerate(order):
        cx = chan0 + chan_p * i
        turn = OY + 9.3 + 0.6 * i
        dest = pin[net]
        if net.endswith("_A"):
            gx = dest[0] - PITCH / 2            # between the lower-row pads, left of the anode pin
            tail = [(gx, turn), (gx, dest[1]), dest]
        else:
            tail = [(dest[0], turn), dest]
        ly = OY + lanes[i]
        r.track([(sx, OY + LED_Y), (sx, ly), (cx, ly), (cx, turn)] + tail, w, B, net)

    outline = [P(0, 0), P(W, 0), P(W, H), P(0, H)]
    for layer in (F, B):
        zone(board, nets["GND"], layer, outline, clearance=0.3)
    for ref, (x, y) in HOLES.items():
        for layer in (F, B):
            ko = pcbnew.ZONE(board)
            ko.SetIsRuleArea(True)
            ko.SetDoNotAllowTracks(True)
            ko.SetDoNotAllowVias(True)
            ko.SetDoNotAllowZoneFills(True)
            ko.SetDoNotAllowPads(False)
            ko.SetDoNotAllowFootprints(False)
            ko.SetLayer(layer)
            ol = ko.Outline()
            ol.NewOutline()
            for i in range(24):
                a = 2 * math.pi * i / 24
                ol.Append(MM(OX + x + 3.3 * math.cos(a)), MM(OY + y + 3.3 * math.sin(a)))
            board.Add(ko)

    Sk, Bk = pcbnew.F_SilkS, pcbnew.B_SilkS
    for k, name in enumerate(BUTTONS):
        add_text(board, Sk, name, OX + COLS[k], OY + 21.7, 1.1, 0.17)
    for k, name in enumerate(LEDS):
        add_text(board, Sk, name.replace("LED ", ""), OX + COLS[k], OY + 29.6, 1.0, 0.15)
    add_text(board, Bk, "MisterFlat front panel Rev A", OX + W / 2, OY + 29.6, 1.0, 0.15)
    add_text(board, Bk, "J1: IDC ribbon to backplane J24", OX + W / 2, OY + 23.0, 0.9, 0.14)
    for ref in ("SW1", "SW2", "SW3", "D1", "D2", "D3"):
        fps[ref].Reference().SetVisible(False)
    fps["J1"].Reference().SetPosition(V(*P(W / 2 + 14.5, 4.5)))

    pcbnew.ZONE_FILLER(board).Fill(board.Zones())
    board.GetDesignSettings().SetAuxOrigin(V(OX, OY))
    path = os.path.join(OUT, f"{PROJECT}.kicad_pcb")
    pcbnew.SaveBoard(path, board)
    print("saved", path)


def main():
    os.makedirs(OUT, exist_ok=True)
    pro = os.path.join(OUT, f"{PROJECT}.kicad_pro")
    if not os.path.exists(pro):
        shutil.copy(os.path.join(OUT, "..", "RevA5", f"{D.PROJECT}.kicad_pro"), pro)
    build_pcb(build_sch())


if __name__ == "__main__":
    main()
