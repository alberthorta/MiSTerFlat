#!/usr/bin/env python3
"""Writes firmware/src/ui/Logos.h: the MiSTer logo PNGs of the display (speed stripes and chrome
pixel letters on black) as C arrays, with their sizes.

    python3 tools/embed_png.py

assets/logo.png            250 x 53, one logo pixel = 6 screen pixels: standby, starting, shutting down
assets/logo-small.png      125 x 26, 3 screen pixels: the menu clock
assets/logo-small-dim.png  the same, darker: the idle clock
"""
import os
import struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
LOGOS = [("kLogo", "assets/logo.png"), ("kLogoSmall", "assets/logo-small.png"),
         ("kLogoSmallDim", "assets/logo-small-dim.png")]

out = ["#pragma once", "", "#include <stddef.h>", "#include <stdint.h>", "",
       "// Generated by tools/embed_png.py from the PNGs in assets/; do not edit. inline: one copy in flash.", ""]
for name, rel in LOGOS:
    data = open(os.path.join(ROOT, rel), "rb").read()
    width, height = struct.unpack(">II", data[16:24])  # the IHDR chunk
    out.append("// {}: {} x {}, {} bytes".format(rel, width, height, len(data)))
    out.append("inline constexpr uint8_t {}Png[] = {{".format(name))
    out += ["    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    out.append("};")
    out.append("inline constexpr int {}Width = {};".format(name, width))
    out.append("inline constexpr int {}Height = {};".format(name, height))
    out.append("")
path = os.path.join(ROOT, "firmware", "src", "ui", "Logos.h")
with open(path, "w") as f:
    f.write("\n".join(out))
print("wrote", os.path.normpath(path))
